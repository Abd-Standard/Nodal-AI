-- 001_initial_schema.sql (Postgres)
--
-- Same tables as the SQLite baseline. Column names are quoted so they keep the
-- camelCase spelling the SQLite schema uses.

CREATE TABLE IF NOT EXISTS agent_results (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "timestamp"     TEXT    NOT NULL,
  "taskType"      TEXT    NOT NULL,
  success         BOOLEAN NOT NULL,
  data            TEXT,
  error           TEXT,
  "correlationId" TEXT
);

CREATE TABLE IF NOT EXISTS spending_records (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  amount      DOUBLE PRECISION NOT NULL,
  "timestamp" BIGINT           NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_spending_records_timestamp
  ON spending_records ("timestamp");

-- Single-row table locked with SELECT ... FOR UPDATE so spending reservations
-- from every instance are serialised against the same window (#822).
CREATE TABLE IF NOT EXISTS spending_lock (
  id INTEGER PRIMARY KEY CHECK (id = 1)
);

INSERT INTO spending_lock (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS agent_state (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS x402_used_nonces (
  nonce      TEXT   PRIMARY KEY,
  used_at_ms BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_x402_nonces_used_at
  ON x402_used_nonces (used_at_ms);
